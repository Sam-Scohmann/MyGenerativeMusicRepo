# =====================================================================
#  Sonic Pi - "Intro" tab  ->  MIDI out + internal synth sound
#  Port: midi_2   Channel: 1
# =====================================================================

use_bpm 200
use_midi_defaults port: "midi_2", channel: 1

# --- sound settings --------------------------------------------------
# Change these to taste
SYNTH_NAME  = :tri        # try :pluck, :piano, :fm, :prophet, :tri, :saw
SYNTH_AMP   = 1
MIDI_VEL    = 85

# --- standard tuning, MIDI note of each open string ------------------
TUNING = {
  "e" => 64,   # high E
  "B" => 59,
  "G" => 55,
  "D" => 50,
  "A" => 45,
  "E" => 40    # low E
}

STEP = 0.25    # one tab column = a 16th note (in beats)


# =====================================================================
#  Parser: turns tab lines into {column => [midi notes]}
# =====================================================================
define :tab_events do |lines|
  ev = {}
  lines.each do |pair|
    name = pair[0]
    body = pair[1]
    base = TUNING[name]
    i = 0
    while i < body.length
      ch = body[i]
      if ch == "("                                  # e.g. (12)
        j = i + 1
        num = ""
        while j < body.length && body[j] != ")"
          num += body[j]
          j += 1
        end
        ev[i] = ev[i] || []
        ev[i] << (base + num.to_i)
        i = j + 1
      elsif ch >= "0" && ch <= "9"                  # e.g. 3, 10, 12
        j = i
        num = ""
        while j < body.length && body[j] >= "0" && body[j] <= "9"
          num += body[j]
          j += 1
        end
        ev[i] = ev[i] || []
        ev[i] << (base + num.to_i)
        i = j
      else
        i += 1                                       # -, h, p, /, \, ~, x ...
      end
    end
  end
  ev
end


# =====================================================================
#  Play one block of tab  (sound + MIDI)
# =====================================================================
define :play_tab do |lines, vel = MIDI_VEL, len = 2.5, synth_name = SYNTH_NAME|
  ev   = tab_events(lines)
  cols = ev.keys.sort
  pos  = 0
  cols.each do |c|
    sleep (c - pos) * STEP
    pos = c
    ev[c].sort.each do |n|
      # ---- MIDI out ----
      midi n,
        sustain:  STEP * len,
        velocity: vel,
        port:     "midi_2",
        channel:  1
      
      # ---- internal synth sound ----
      use_synth synth_name
      play n,
        amp:      SYNTH_AMP,
        release:  STEP * len,
        sustain:  STEP * len * 0.5,
        decay:    STEP * len * 0.3
    end
  end
  # pad out to the end of the longest tab line so sections keep their timing
  total = lines.map { |p| p[1].length }.max
  sleep (total - pos) * STEP if total > pos
end


